from sqlalchemy import (
    Column,
    Integer,
    String,
    Numeric,
    DateTime,
    ForeignKey,
    Enum,
    Boolean,
    UniqueConstraint,
    text,
    func
)
from sqlalchemy.orm import relationship
from src.config.database import Base


class Farmer(Base):
    """
    Farmer entity storing credentials and profile information.
    """
    __tablename__ = "Farmer"

    farmer_id = Column(Integer, primary_key=True, autoincrement=True)
    fname = Column(String(50), nullable=False)
    lname = Column(String(50), nullable=False)
    email = Column(String(100), unique=True, nullable=False, index=True)
    password = Column(String(255), nullable=False)

    # Relationships
    cows = relationship("Cow", back_populates="farmer", cascade="all, delete-orphan")
    alerts = relationship("Alert", back_populates="farmer", cascade="all, delete-orphan")


class Cow(Base):
    """
    Dairy cow registered under a farmer, tracking health status.
    """
    __tablename__ = "Cow"

    cow_id = Column(Integer, primary_key=True, autoincrement=True)
    farmer_id = Column(Integer, ForeignKey("Farmer.farmer_id", ondelete="CASCADE"), nullable=False, index=True)
    cow_tag = Column(String(20), nullable=False)
    breed = Column(String(50), nullable=False)
    age = Column(Integer, nullable=False)
    health_status = Column(
        Enum("Healthy", "At Risk", "Pending", name="health_status_enum"),
        nullable=False,
        default="Pending",
        server_default=text("'Pending'")
    )
    last_tested = Column(DateTime, nullable=True)

    __table_args__ = (
        UniqueConstraint("farmer_id", "cow_tag", name="uq_farmer_cow_tag"),
    )

    # Relationships
    farmer = relationship("Farmer", back_populates="cows")
    sensor_readings = relationship("SensorReading", back_populates="cow", cascade="all, delete-orphan")
    detection_results = relationship("DetectionResult", back_populates="cow", cascade="all, delete-orphan")


class SensorReading(Base):
    """
    Raw sensor data acquired from ESP32 IoT node (Temperature, pH, Electrical Conductivity).
    """
    __tablename__ = "Sensor_Reading"

    reading_id = Column(Integer, primary_key=True, autoincrement=True)
    cow_id = Column(Integer, ForeignKey("Cow.cow_id", ondelete="CASCADE"), nullable=False, index=True)
    temperature = Column(Numeric(5, 2), nullable=False)
    pH = Column(Numeric(4, 2), nullable=False)
    electrical_conductivity = Column(Numeric(6, 2), nullable=False)
    reading_time = Column(DateTime, nullable=False)

    # Relationships
    cow = relationship("Cow", back_populates="sensor_readings")
    detection_result = relationship("DetectionResult", back_populates="sensor_reading", uselist=False, cascade="all, delete-orphan")


class DetectionResult(Base):
    """
    Inference result generated by the Random Forest model for a specific sensor reading.
    """
    __tablename__ = "Detection_Result"

    result_id = Column(Integer, primary_key=True, autoincrement=True)
    cow_id = Column(Integer, ForeignKey("Cow.cow_id", ondelete="CASCADE"), nullable=False, index=True)
    reading_id = Column(
        Integer,
        ForeignKey("Sensor_Reading.reading_id", ondelete="CASCADE", name="fk_detection_reading"),
        unique=True,
        nullable=False
    )
    prediction = Column(
        Enum("Mastitis Present", "Mastitis Absent", name="prediction_enum"),
        nullable=False
    )
    confidence_score = Column(Numeric(5, 2), nullable=True)
    detection_time = Column(DateTime, nullable=False)

    # Relationships
    cow = relationship("Cow", back_populates="detection_results")
    sensor_reading = relationship("SensorReading", back_populates="detection_result")
    alert = relationship("Alert", back_populates="detection_result", uselist=False, cascade="all, delete-orphan")


class Alert(Base):
    """
    High-priority notification generated when Mastitis is detected.
    """
    __tablename__ = "Alert"

    alert_id = Column(Integer, primary_key=True, autoincrement=True)
    result_id = Column(
        Integer,
        ForeignKey("Detection_Result.result_id", ondelete="CASCADE"),
        unique=True,
        nullable=False
    )
    farmer_id = Column(Integer, ForeignKey("Farmer.farmer_id", ondelete="CASCADE"), nullable=False, index=True)
    message = Column(String(255), nullable=False)
    status = Column(
        Enum("Read", "Unread", name="alert_status_enum"),
        nullable=False,
        default="Unread",
        server_default=text("'Unread'")
    )
    send_time = Column(DateTime, nullable=False)

    # Relationships
    farmer = relationship("Farmer", back_populates="alerts")
    detection_result = relationship("DetectionResult", back_populates="alert")


class OTPCode(Base):
    """
    Verification OTP codes for Two-Factor Authentication and Password Reset.
    """
    __tablename__ = "otp_codes"

    id = Column(Integer, primary_key=True, autoincrement=True)
    email = Column(String(100), nullable=False, index=True)
    code = Column(String(6), nullable=False)
    purpose = Column(
        Enum("login", "reset_password", name="otp_purpose_enum"),
        nullable=False
    )
    expires_at = Column(DateTime, nullable=False)
    is_used = Column(Boolean, default=False, server_default=text("0"), nullable=False)
    created_at = Column(DateTime, server_default=func.now(), nullable=False)
